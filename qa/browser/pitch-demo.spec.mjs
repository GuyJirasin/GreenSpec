import {test,expect} from '@playwright/test';
import {fixture,id} from './fixture.mjs';
import {mkdirSync} from 'node:fs';
test('prepared demo flow: ready real file, A/B, wording, complete review, final, reload, new round',async({page})=>{
 const f=await fixture(page,{run:true});
 await page.goto(`/#workspace?project=${id}&tab=documents`);
 await expect(page.getByRole('button',{name:'Analyze project'})).toBeEnabled();
 await expect(page.locator('.unified-project-nav')).toHaveCount(1);await expect(page.locator('.sidebar').getByText(/demo/i)).toHaveCount(0);expect(await page.locator('main').innerText()).not.toMatch(/demo/i);await expect(page.locator('main > .tabs')).toHaveCount(0);
 await page.getByRole('button',{name:'Analyze project'}).click();
 await expect(page.getByRole('heading',{name:'Material hotspots'})).toBeVisible();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Recommendations',exact:true}).click();
 await page.getByRole('button',{name:'Compare options',exact:true}).first().click();
 await page.getByRole('button',{name:'Select Option B',exact:true}).click();
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Revised Specification'}).click();
 await page.getByRole('button',{name:'Unlock to edit',exact:true}).click();
 await page.getByRole('textbox',{name:'Revised requirement'}).fill('คอนกรีตที่แก้ไขโดยผู้ใช้สำหรับโครงการ');
 await page.getByRole('button',{name:'Save wording',exact:true}).click();
 await expect(page.getByRole('button',{name:'Approve',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Approve',exact:true}).click();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Impact & Summary'}).click();
 await expect(page.getByRole('button',{name:'Finalize'})).toBeDisabled();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Recommendations',exact:true}).click();
 for(let n=0;n<3;n++)await page.getByRole('button',{name:'Reject',exact:true}).first().click();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Impact & Summary'}).click();
 await expect(page.getByRole('button',{name:'Finalize'})).toBeEnabled();await page.getByRole('button',{name:'Finalize'}).click();
 await expect(page.getByRole('heading',{name:'Final revision'})).toBeVisible();
 await page.reload();await expect(page.getByRole('heading',{name:'Final revision'})).toBeVisible();
 await page.locator('.unified-project-nav').getByRole('link',{name:'Revised Specification'}).click();
 await expect(page.getByRole('textbox',{name:'Revised requirement'})).toHaveValue('คอนกรีตที่แก้ไขโดยผู้ใช้สำหรับโครงการ');await expect(page.getByRole('textbox',{name:'Revised requirement'})).toBeDisabled();
 mkdirSync('screenshots',{recursive:true});await page.screenshot({path:'screenshots/pitch-demo-desktop.png',fullPage:true});
 await page.locator('.unified-project-nav').getByRole('link',{name:'Documents',exact:true}).click();await page.getByRole('button',{name:'Analyze project'}).click();
 await expect(page.locator('.demo-round-toolbar option')).toHaveCount(2);
 await page.getByRole('button',{name:'ไทย',exact:true}).click();await expect(page.locator('.header-context .badge')).toHaveText('DEMO');expect(await page.locator('main').innerText()).not.toMatch(/demo/i);
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'screenshots/pitch-demo-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(f.requests.filter(r=>r.path.includes('/functions/v1/analyze'))).toHaveLength(0);expect(f.calls.filter(r=>['gs_finalize','gs_review_change'].includes(r.name))).toHaveLength(0);expect(f.errors).toEqual([]);
});
